% Offset de las etiquetas perpendicular a la curva
s  = 0.06 * max(rx, ry);   % tamaño del desplazamiento
for ii = 1:numel(idx_label)
    i = idx_label(ii);
    % Tangente local
    if i==1
        t = [x(2)-x(1), y(2)-y(1)];
    elseif i==N
        t = [x(N)-x(N-1), y(N)-y(N-1)];
    else
        t = [x(i+1)-x(i-1), y(i+1)-y(i-1)];
    end
    % Normal unitaria
    n = [-t(2), t(1)];
    if norm(n) < 1e-12, n = [1,0]; else, n = n/norm(n); end

    off = s*n;
    text(x(i)+off(1), y(i)+off(2), sprintf('%.0f°', Kdeg(i)), ...
        'FontSize',9, 'FontWeight','bold', 'Color',[0.1 0.1 0.1], ...
        'HorizontalAlignment','center','VerticalAlignment','middle', ...
        'BackgroundColor','w','Margin',2, 'EdgeColor',[0.8 0.8 0.8]);
